// Injecting a .fw update package into a factory .img.
//
// A .fw is not a partition image — it is a gzip'd tar that the device installs
// by running its `./update` as root. There is no OS in maskrom mode to run it,
// so the package cannot simply be "flashed". Instead:
//
//   1. the package bytes go into the unused tail of the rootfs PARTITION.
//      parameter.txt gives rootfs 7,340,032 sectors (3.5 GiB) while rootfs.img
//      is 2,399,595,520 bytes (2.235 GiB), leaving ~1.26 GiB that nothing ever
//      touches — only `userdata:grow` grows, and it is a different partition;
//   2. a one-shot systemd unit is injected into the ext2 rootfs. On first boot
//      it dd's those bytes back off the disk and hands them to the stock
//      updater, exactly as the vendor's own network path does.
//
// The payload therefore costs no filesystem space, and the only filesystem
// changes are three small files. `/etc/rc.local` is deliberately left alone: it
// runs /etc/init.d/rcS and is the most load-bearing script on the device.
//
// Two device behaviours shape the injected script, both learned the hard way:
//   - `birddog-update-wrapper` stops BirdDogRunner and never restarts it, so an
//     installer that just exits leaves a dark HDMI output that looks bricked.
//     It reboots instead.
//   - the done-marker is written BEFORE the update runs. A package that panics
//     the box must not reinstall itself on every boot.

import { Ext2 } from './ext2.js';

export const PAYLOAD_ALIGN_SECTORS = 2048;  // 1 MiB
const SECTOR_SIZE = 512;

const UNIT_PATH = '/etc/systemd/system';
const UNIT_NAME = 'BirdDogInject.service';
const SCRIPT_DIR = '/usr/local/bin';
const SCRIPT_NAME = 'bd-inject.sh';
const WANTS_DIR = '/etc/systemd/system/multi-user.target.wants';

export function injectScript({ sector, bytes, marker = '/userdata/.bd-inject-done' }) {
  const count = Math.ceil(bytes / SECTOR_SIZE);
  return `#!/bin/sh
# Generated by birddog-play-flasher. Applies a .fw package that was written
# into the unused tail of the rootfs partition when this image was flashed.
MARK=${marker}
LOG=/userdata/bd-inject.log
SKIP=${sector}
COUNT=${count}
BYTES=${bytes}
PKG=/tmp/bd-inject.fw

[ -f "$MARK" ] && exit 0
exec >>"$LOG" 2>&1
echo "=== bd-inject $(date) ==="

# The partition device, not the whole disk: the offset is partition-relative, so
# it stays correct however the eMMC and any SD card end up numbered.
part=$(awk '$2 == "/" && $1 ~ /^\\/dev\\// {print $1; exit}' /proc/mounts)
[ -z "$part" ] && part=$(readlink -f /dev/root 2>/dev/null)
if [ -z "$part" ] || [ ! -b "$part" ]; then
  echo "cannot find the root partition device; giving up"
  exit 1
fi
echo "root partition: $part"

dd if="$part" bs=512 skip=$SKIP count=$COUNT 2>/dev/null | head -c $BYTES > "$PKG"
size=$(wc -c < "$PKG")
if [ "$size" != "$BYTES" ]; then
  echo "short read: got $size of $BYTES bytes"
  exit 1
fi
# A .fw is gzip; if the first two bytes are not 1f 8b the payload is not there.
magic=$(dd if="$PKG" bs=1 count=2 2>/dev/null | od -An -tx1 | tr -d ' \\n')
if [ "$magic" != "1f8b" ]; then
  echo "payload is not a gzip stream (magic $magic); giving up"
  exit 1
fi

# Before installing, not after: a package that kills the box must not be
# reinstalled on every subsequent boot.
touch "$MARK"

echo "handing $PKG to the stock updater"
echo "$PKG" > /tmp/birddog-update-package
: > /tmp/birddog-update-lock
systemctl start BirdDogUpdateRunner

# birddog-update-wrapper clears the lock on the way out, whatever the outcome.
i=0
while [ -f /tmp/birddog-update-lock ] && [ $i -lt 900 ]; do
  sleep 2
  i=$((i + 1))
done
echo "updater finished after $((i * 2))s"

# The wrapper stops BirdDogRunner and only ever restarts it by rebooting.
# Exiting here would leave the device with no video output, looking bricked.
sync
reboot
`;
}

export function injectUnit() {
  return `[Unit]
Description=BirdDog PLAY injected firmware package
After=multi-user.target
RequiresMountsFor=/userdata
ConditionPathExists=!/userdata/.bd-inject-done

[Service]
Type=oneshot
ExecStart=${SCRIPT_DIR}/${SCRIPT_NAME}

[Install]
WantedBy=multi-user.target
`;
}

/**
 * Work out where the package goes and what to change in the filesystem.
 *
 * @param {Blob} rootfsBlob      the rootfs.img slice of the .img
 * @param {number} rootfsSectors size of the rootfs PARTITION from parameter.txt
 * @param {number} payloadBytes  size of the .fw
 * @returns {{relativeSector:number, patches:{offset:number,bytes:Uint8Array}[]}}
 */
export async function planInjection(rootfsBlob, rootfsSectors, payloadBytes) {
  const fs = await Ext2.open(rootfsBlob);
  const fsBytes = fs.sb.blocksCount * fs.sb.blockSize;
  const fsSectors = Math.ceil(fsBytes / SECTOR_SIZE);
  if (fsSectors > rootfsBlob.size / SECTOR_SIZE) {
    throw new Error('rootfs filesystem claims to be larger than its image');
  }

  const relativeSector = Math.ceil(fsSectors / PAYLOAD_ALIGN_SECTORS) * PAYLOAD_ALIGN_SECTORS;
  const payloadSectors = Math.ceil(payloadBytes / SECTOR_SIZE);
  const spare = rootfsSectors - relativeSector;
  if (payloadSectors > spare) {
    throw new Error(
      `package needs ${payloadSectors} sectors but only ${spare} are free after the filesystem`,
    );
  }

  const script = injectScript({ sector: relativeSector, bytes: payloadBytes });
  const enc = new TextEncoder();
  await fs.createFile(SCRIPT_DIR, SCRIPT_NAME, enc.encode(script), 0o755);
  await fs.createFile(UNIT_PATH, UNIT_NAME, enc.encode(injectUnit()), 0o644);
  await fs.createSymlink(WANTS_DIR, UNIT_NAME, `${UNIT_PATH}/${UNIT_NAME}`);
  await fs.flushMetadata();

  return {
    relativeSector,
    payloadSectors,
    spareSectors: spare,
    fsSectors,
    patches: fs.patches(),
  };
}
